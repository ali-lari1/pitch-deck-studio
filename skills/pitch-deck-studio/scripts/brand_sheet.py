#!/usr/bin/env python3
"""Render a one-page brand sheet (wordmark, palette, type, usage) from brand.json + preset.

Usage:
    python3 brand_sheet.py <project_dir> [--out brand-sheet.html]
"""
import html
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import build  # noqa: E402  (reuses preset merge + theme tokens)


def main(argv):
    if len(argv) < 2 or argv[1] in ("-h", "--help"):
        print(__doc__)
        return 0
    root = os.path.abspath(argv[1])
    out = argv[argv.index("--out") + 1] if "--out" in argv else "brand-sheet.html"
    b = build.resolve_brand(root, {})
    css, link = build.theme_css(b)
    c, f = b.get("colors", {}), b.get("fonts", {})
    name = html.escape(b.get("name", "Brand"))
    logo = b.get("logo")
    mark = '<img src="%s" alt="" style="height:96px">' % html.escape(logo) if logo else ""
    roles = [("bg", "Background"), ("fg", "Text"), ("accent", "Accent: meaning only"), ("muted", "Muted text"),
             ("surface", "Surface"), ("line", "Rules")]
    sw = "".join(
        '<div class="sw"><div class="chip" style="background:%s"></div><b>%s</b><span>%s</span></div>' % (
            c.get(k), html.escape(lbl), html.escape(str(c.get(k, "")).upper())) for k, lbl in roles if c.get(k))
    doc = """<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>%(name)s brand sheet</title>%(link)s<style>%(css)s
*{box-sizing:border-box;margin:0;padding:0}
body{background:var(--bg);color:var(--fg);font-family:var(--f-body);padding:72px clamp(20px,6vw,96px);max-width:1280px;margin:0 auto}
.lab{font-size:13px;letter-spacing:var(--label-track);text-transform:uppercase;color:var(--muted);margin:64px 0 18px;border-top:1px solid var(--line);padding-top:16px}
.word{display:flex;align-items:center;gap:28px;font-family:var(--f-display);font-weight:var(--d-weight);letter-spacing:var(--d-track);
 text-transform:var(--d-case);font-size:clamp(64px,11vw,148px);line-height:1}
.word .dot{color:var(--accent)}
.inv{background:var(--inv-bg);color:var(--inv-fg);padding:48px;margin-top:28px;border-radius:var(--radius)}
.inv .word{font-size:clamp(40px,6vw,72px)}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(170px,1fr));gap:20px}
.sw .chip{height:110px;border-radius:var(--radius);border:1px solid var(--line);margin-bottom:12px}
.sw b{display:block;font-size:15px}.sw span{font-family:var(--f-mono);font-size:13px;color:var(--muted)}
.t1{font-family:var(--f-display);font-weight:var(--d-weight);letter-spacing:var(--d-track);text-transform:var(--d-case);font-size:56px;line-height:1.05}
.t2{font-size:22px;line-height:1.5;max-width:760px;margin-top:16px;color:var(--muted)}
.t3{font-family:var(--f-num);font-weight:var(--n-weight);font-size:96px;color:var(--accent);line-height:1;margin-top:24px}
.meta{font-family:var(--f-mono);font-size:13px;color:var(--muted);margin-top:10px}
ul{margin-left:18px;line-height:1.8;font-size:17px}
</style></head><body>
<div class="word">%(mark)s<span>%(name)s<span class="dot">.</span></span></div>
<div class="inv"><div class="word"><span>%(name)s<span class="dot">.</span></span></div></div>
<div class="lab">Palette</div><div class="grid">%(sw)s</div>
<div class="lab">Typography</div>
<div class="t1">Headlines state the takeaway.</div>
<div class="meta">Display: %(fd)s, weight %(dw)s</div>
<p class="t2">Body copy is calm and specific. It explains with numbers rather than adjectives and is set in %(fb)s for legibility at any size.</p>
<div class="meta">Body: %(fb)s</div>
<div class="t3">$4.2M · 118%%</div><div class="meta">Numbers: %(fn)s</div>
<div class="lab">Usage</div>
<ul><li>One accent colour, used only for meaning: the key number, the highlighted bar, "us" on a chart.</li>
<li>Wordmark: the name set in the display face. Keep clear space equal to the cap height. No effects or outlines, and never stretch it.</li>
<li>Photography: real product, people and places. Use full-bleed or framed, never clip-art.</li>
<li>Layout: generous margins, hairline rules instead of boxes, one focal point per page.</li>
<li>This is a starting identity generated by pitch-deck-studio, not a trademark-cleared logo.</li></ul>
</body></html>""" % {"name": name, "link": link, "css": css, "mark": mark, "sw": sw,
                      "fd": html.escape(str(f.get("display"))), "dw": f.get("display_weight"),
                      "fb": html.escape(str(f.get("body"))), "fn": html.escape(str(f.get("numbers", f.get("display"))))}
    path = os.path.join(root, out)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(doc)
    print("wrote " + path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
